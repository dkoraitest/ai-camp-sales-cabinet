def filler(who, p):
    return (random.choice(F_MGR if who=="manager" else F_CLI) + ", ") if random.random() < p else ""

def say(who, text, p):
    """Реплика с филлером: после филлера фраза продолжается со строчной буквы."""
    f = filler(who, p)
    if not f: return text
    return f + (text[0].lower() + text[1:] if text[:1].isupper() else text)

def build_call(mid, stage, seg, lead, idx, dt):
    m = MGRS[mid]; t = []
    add = lambda who, text: t.append({"who": who, "text": text})
    # у исходных лидов встречаются отрасли вне карты сегментов — маппим на ближайшую
    S = SEGMENTS.get(seg) or SEGMENTS[MAP_SEG.get(seg, "Дистрибуция")]
    weak_start = (random.random() > m["asks_first"] + .25) and stage == "first_contact"
    add("manager", (random.choice(GREET_WEAK) if weak_start else random.choice(GREET))
        .format(name=lead["contact"].split()[0], mgr=m["name"].split()[0]))
    add("client", random.choice(NOISE_CLI if random.random() < .18 else ACK_CLI))

    said = set()
    def pick(pool):
        fresh = [x for x in pool if x not in said] or pool
        x = random.choice(fresh); said.add(x); return x

    asks = random.random() < m["asks_first"]
    if asks:
        deep = m["asks_first"] > .5
        for q, key in random.sample(SIT_QA, k=2 if deep else 1):
            add("manager", say("manager", q, m["filler"]))
            add("client", say("client", pick(S[key]), .3))
        for q, key in random.sample(PAIN_QA, k=2 if deep else 1):
            add("manager", say("manager", q, m["filler"]))
            add("client", say("client", pick(S[key]), .3))
        if random.random() < m["qual"]:
            add("manager", say("manager", random.choice(STAKE_Q), m["filler"]))
            add("client", say("client", random.choice(STAKE_A), .25))
        if random.random() < m["to_money"]:
            add("manager", random.choice(MONEY_Q))
            add("client", say("client", random.choice(S["cost"]), .4))
    else:
        add("manager", say("manager", pick(PRODUCT), m["filler"]))
        add("client", random.choice(["Понятно.", "Угу.", "Ясно.", "Хорошо."]))
        add("manager", pick(PRODUCT))
        add("client", random.choice(["Ага.", "Понятно.", "Интересно."]))

    if stage in ("demo", "proposal", "negotiation") or random.random() < .5:
        add("client", random.choice(PRICE_ASK))
        add("manager", random.choice(PRICE_ANS))
        if random.random() < .75:
            o = random.choice(OBJ); add("client", o)
            add("manager", random.choice(OBJ_ANS[m["obj_style"]]))
            if m["obj_style"] == "discount" and random.random() < .5:
                add("client", "А больше можете?")
                add("manager", "Я уточню у руководителя и вернусь.")

    good_close = random.random() < m["next_step"]
    if good_close:
        pool = CLOSE_STRONG if m["asks_first"] > .5 else CLOSE_MID
        add("manager", random.choice(pool).format(
            day=random.choice(["во вторник","в среду","в четверг","в понедельник"]),
            time=random.choice(["в одиннадцать","в пятнадцать часов","в десять","после обеда"])))
        add("client", random.choice(CLI_OK))
    else:
        add("manager", random.choice(CLOSE_WEAK))
        add("client", random.choice(CLI_MEH))

    money_done = any(q in tt["text"] for tt in t for q in MONEY_Q)
    disc = ("потребность доведена до цифры" if money_done else
            "ситуация выяснена, до денег не дошли" if asks else
            "презентация без выявления")
    outcome = disc + (", следующий шаг с датой" if good_close else ", next step не зафиксирован")
    return {"id": f"c{idx:03d}", "date": dt.isoformat(timespec="minutes"),
            "manager_id": mid, "lead_id": lead["id"], "stage": stage,
            "direction": random.choice(["outbound","outbound","inbound"]),
            "duration_min": max(3, int(len(t) * random.uniform(1.2, 2.2))),
            "outcome": outcome, "transcript": t}

