def build_chat(mid, lead, idx, dt, kind):
    tmpl = {"good":CHAT_GOOD,"bad":CHAT_BAD,"price":CHAT_PRICE,"short":CHAT_SHORT}[kind]
    n = lead["contact"].split()[0]
    msgs, cur = [], dt
    for who, text in tmpl:
        cur += timedelta(minutes=random.randint(20, 900))
        msgs.append({"who":who,"ts":cur.isoformat(timespec="minutes"),"text":text.format(n=n)})
    outcome = {"good":"скрытое возражение снято через переписку, решение ускорено",
               "bad":"серия напоминаний без нового аргумента, переписка затухла",
               "price":"торг о скидке ушёл в мессенджер, ценность не вернулась",
               "short":"прайс отправлен без контекста, диалог закончился"}[kind]
    return {"id": f"ch{idx:03d}", "channel": random.choice(["whatsapp","whatsapp","telegram"]),
            "manager_id": mid, "lead_id": lead["id"],
            "stage": random.choice(["discovery","demo","proposal","negotiation"]),
            "date_start": dt.isoformat(timespec="minutes"),
            "date_end": msgs[-1]["ts"], "messages_count": len(msgs),
            "outcome": outcome, "messages": msgs}

def main():
    src = json.loads((ROOT/"data/b2b/dataset.json").read_text(encoding="utf-8"))
    anchors_calls, anchors_chats = src["calls"], src["chats"]
    leads = list(src["leads"])
    start = datetime(2026, 6, 15, 9, 0)

    # расширяем пул лидов
    used = {l["company"] for l in leads}
